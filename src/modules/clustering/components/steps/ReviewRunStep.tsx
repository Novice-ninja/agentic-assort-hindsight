import { useEffect, useMemo, useRef, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { AIStrip } from '@shared/components/primitives';
import { Button } from '@shared/components/vendor/impact-ui';
import { capReviewVariants, hasCustomVariant } from '../../services/mapGeneratedVariants';
import { activeVariantCount } from '../../services/variantMath';
import type { ClusteringAttribute, ClusteringRun, Variant } from '../../types';
import { ReviewAttributesPanel } from '../ReviewAttributesPanel';
import { ReviewMetricTiles } from '../ReviewMetricTiles';
import { VariantCardsSkeleton } from '../ResumeSkeletons';
import { VariantCard } from '../VariantCard';
import sections from '@shared/styles/wizardSections.module.css';
import { AgentSectionStatus } from '../AgentSectionStatus';
import agentFlow from '../agentFlow.module.css';
import styles from '../wizard.module.css';

export interface ReviewRunStepProps {
  attributes: ClusteringAttribute[];
  variants: Variant[];
  run: ClusteringRun | null;
  cutoff: number;
  kValueCount: number;
  startingPoints: number;
  inputNeededReason?: string;
  /**
   * True once "Confirm and Generate Variant" has stored variants for this plan. Keeps
   * Attribute Picks — Impact hidden until then.
   */
  showAttributePicks: boolean;
  confirming?: boolean;
  /** Disable Confirm because the visible variants already match the checkboxes. */
  confirmDisabled?: boolean;
  attributesLoading?: boolean;
  attributesFailed?: boolean;
  variantsLoading?: boolean;
  variantsFailed?: boolean;
  onRetryAttributes?: () => void;
  onRetryVariants?: () => void;
  onToggleAttribute: (id: string, selected: boolean) => void;
  onConfirm: () => void;
  onRemoveVariant: (id: string) => void;
  onRestoreVariant: (id: string) => void;
  onRemoveAll: () => void;
  onRestoreAll: () => void;
  onOpenCustomVariant: () => void;
  /** Describe Your Plan mirror: the agent drives this step; controls are disabled. */
  readOnly?: boolean;
  /** Section the agent is currently filling (cyan stroke). */
  highlightedSection?: 'attributes' | 'variants';
}

export function ReviewRunStep({
  attributes,
  variants,
  cutoff,
  kValueCount,
  startingPoints,
  showAttributePicks,
  confirming,
  confirmDisabled,
  attributesLoading,
  attributesFailed,
  variantsLoading,
  variantsFailed,
  onRetryAttributes,
  onRetryVariants,
  onToggleAttribute,
  onConfirm,
  onRemoveVariant,
  onRestoreVariant,
  onRemoveAll,
  onRestoreAll,
  onOpenCustomVariant,
  readOnly = false,
  highlightedSection,
}: ReviewRunStepProps) {
  const { t } = useTranslation(['clustering', 'common']);
  const picksRef = useRef<HTMLElement | null>(null);
  const displayedVariants = useMemo(() => capReviewVariants(variants), [variants]);
  const [selectedVariantId, setSelectedVariantId] = useState<string | null>(
    () => displayedVariants[0]?.id ?? null,
  );
  const active = activeVariantCount(displayedVariants);

  useEffect(() => {
    if (!showAttributePicks) return;
    picksRef.current?.scrollIntoView?.({ behavior: 'smooth', block: 'start' });
  }, [showAttributePicks]);

  useEffect(() => {
    if (displayedVariants.length === 0) {
      setSelectedVariantId(null);
      return;
    }
    if (!displayedVariants.some((variant) => variant.id === selectedVariantId)) {
      setSelectedVariantId(displayedVariants[0]?.id ?? null);
    }
  }, [displayedVariants, selectedVariantId]);

  const selectedAttributeCount = attributes.filter((attr) => attr.userSelected).length;
  const cardOptionCount = kValueCount * startingPoints;
  const allRemoved = active === 0;
  const variantsUnavailable = Boolean(variantsLoading || variantsFailed);
  const customVariantDisabled =
    readOnly || variantsUnavailable || hasCustomVariant(variants);
  const selectedVariant =
    displayedVariants.find((variant) => variant.id === selectedVariantId) ??
    displayedVariants[0] ??
    null;
  const selectedSummary = selectedVariant?.aiSummary?.trim() ?? '';
  // Temporary copy until the custom-variant API returns aiSummary. Remove with the key.
  const summaryText =
    selectedSummary ||
    (selectedVariant && !selectedVariant.isAutoGenerated
      ? t('review.customVariantFallbackSummary')
      : t('review.noInsight'));

  return (
    <div className={[sections.step, styles.reviewStep].join(' ')}>
      <ReviewAttributesPanel
        attributes={attributes}
        cutoff={cutoff}
        onToggle={onToggleAttribute}
        onConfirm={onConfirm}
        confirming={confirming}
        confirmDisabled={confirmDisabled}
        loading={attributesLoading}
        loadFailed={attributesFailed}
        onRetry={onRetryAttributes}
        readOnly={readOnly}
        highlighted={highlightedSection === 'attributes'}
      />
      {showAttributePicks ? (
        <section
          ref={picksRef}
          className={[
            sections.sectionWrapper,
            highlightedSection === 'variants' ? agentFlow.sectionGlow : '',
          ]
            .filter(Boolean)
            .join(' ')}
          aria-labelledby="attribute-picks-title"
          data-testid="attribute-picks"
          data-highlighted={highlightedSection === 'variants' ? 'true' : undefined}
        >
          {highlightedSection === 'variants' ? <AgentSectionStatus section="variants" /> : null}
          <div className={[sections.toolbar, styles.toolbarSpread].join(' ')}>
            <div className={styles.sectionHeading}>
              <span id="attribute-picks-title" className={styles.reviewTitle}>
                {t('review.attributePicksTitle')}
              </span>
              <p className={styles.reviewSubtitle}>{t('review.attributePicksSubtitle')}</p>
            </div>
            <div className={styles.picksToolbar}>
              <Button
                variant="tertiary"
                onClick={onOpenCustomVariant}
                disabled={customVariantDisabled}
              >
                {t('review.customVariant')}
              </Button>
              <Button
                variant="secondary"
                onClick={allRemoved ? onRestoreAll : onRemoveAll}
                disabled={readOnly || variantsUnavailable}
              >
                {allRemoved ? t('review.restoreAll') : t('review.removeAll')}
              </Button>
            </div>
          </div>
          <AIStrip
            className={styles.reviewAiStrip}
            text={summaryText}
            loading={variantsLoading}
            showAskButton={false}
            showTooltip={!variantsUnavailable && summaryText !== t('review.noInsight')}
          />
          {variantsLoading ? <VariantCardsSkeleton /> : null}
          {variantsFailed && !variantsLoading ? (
            <div role="alert">
              <p className={sections.empty}>{t('errors.generateVariantFailed')}</p>
              {onRetryVariants ? (
                <Button variant="secondary" onClick={onRetryVariants}>
                  {t('common:actions.retry', 'Retry')}
                </Button>
              ) : null}
            </div>
          ) : null}
          {!variantsLoading && !variantsFailed ? (
            <>
              <div className={[styles.variantGrid, sections.fullWidth].join(' ')}>
                {displayedVariants.map((variant) => (
                  <VariantCard
                    key={variant.id}
                    variant={variant}
                    attributes={attributes}
                    attributeCount={variant.metrics?.attributeCount ?? selectedAttributeCount}
                    kValueCount={variant.metrics?.kValueCount ?? kValueCount}
                    startingPoints={variant.metrics?.startingPoints ?? startingPoints}
                    optionCount={variant.metrics?.optionCount ?? cardOptionCount}
                    disableRemove={active <= 1 && !variant.removed}
                    readOnly={readOnly}
                    selected={variant.id === selectedVariant?.id}
                    onSelect={() => setSelectedVariantId(variant.id)}
                    onRemove={() => onRemoveVariant(variant.id)}
                    onRestore={() => onRestoreVariant(variant.id)}
                  />
                ))}
              </div>
              <ReviewMetricTiles metrics={selectedVariant?.metrics ?? null} />
            </>
          ) : null}
        </section>
      ) : null}
    </div>
  );
}
