import { useTranslation } from 'react-i18next';
import { Button, ImpactBadge } from '@shared/components/vendor/impact-ui';
import { variantCardTitle } from '../services/reviewVariantDisplay';
import type { ClusteringAttribute, Variant } from '../types';
import styles from './wizard.module.css';

export interface VariantCardProps {
  variant: Variant;
  attributes: ClusteringAttribute[];
  attributeCount: number;
  kValueCount: number;
  startingPoints: number;
  optionCount: number;
  disableRemove: boolean;
  selected?: boolean;
  onSelect?: () => void;
  onRemove: () => void;
  onRestore: () => void;
  /** Describe Your Plan mirror: Remove / Restore are disabled without the "last variant" hint. */
  readOnly?: boolean;
}

export function VariantCard({
  variant,
  attributes,
  attributeCount,
  kValueCount,
  startingPoints,
  optionCount,
  disableRemove,
  selected,
  onSelect,
  onRemove,
  onRestore,
  readOnly = false,
}: VariantCardProps) {
  const { t } = useTranslation('clustering');
  const cardName = variantCardTitle(variant.name, {
    custom: !variant.isAutoGenerated,
    fallback: t('review.customVariant'),
    variantId: variant.id,
  });
  const labels = variant.attributeIds
    .map((id) => attributes.find((attr) => attr.id === id))
    .filter((attr): attr is ClusteringAttribute => Boolean(attr));

  return (
    <article
      className={[
        styles.variantCard,
        variant.removed ? styles.variantRemoved : '',
        selected ? styles.variantSelected : '',
      ]
        .filter(Boolean)
        .join(' ')}
      data-removed={variant.removed || undefined}
      data-selected={selected || undefined}
      onClick={onSelect}
    >
      <div className={styles.variantHeader}>
        <div className={styles.variantHeaderMain}>
          <span className={styles.variantName}>{cardName}</span>
          {/* <ImpactBadge
            label={reviewVariantDisplayName(variant, t)}
            variant="subtle"
            size="small"
            color="info"
            disabled={variant.removed}
          /> */}
        </div>
        <span
          className={styles.variantAction}
          title={disableRemove && !readOnly ? t('review.lastVariant') : undefined}
          onClick={(event) => event.stopPropagation()}
        >
          {variant.removed ? (
            <Button variant="secondary" onClick={onRestore} size="small" disabled={readOnly}>
              {t('review.restore')}
            </Button>
          ) : (
            <Button
              variant="secondary"
              onClick={onRemove}
              size="small"
              disabled={readOnly || disableRemove}
            >
              {t('review.remove')}
            </Button>
          )}
        </span>
      </div>
      <div className={styles.chips}>
        {labels.map((attr) => (
          <ImpactBadge
            key={attr.id}
            label={t(attr.labelKey, { defaultValue: attr.label ?? attr.id })}
            variant="subtle"
            size="small"
            disabled={variant.removed}
          />
        ))}
      </div>
      <p className={styles.variantSummary}>
        <span className={styles.variantSummaryLead}>{t('review.variantSummaryLead')}</span>{' '}
        <span className={styles.variantSummaryMetrics}>
          {t('review.variantSummaryMetrics', {
            attributes: attributeCount,
            k: kValueCount,
            starts: startingPoints,
            total: optionCount,
          })}
        </span>
      </p>
    </article>
  );
}
