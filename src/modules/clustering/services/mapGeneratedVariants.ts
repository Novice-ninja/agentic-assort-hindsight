import type { GeneratedVariantDto, GenerateVariantsResponse } from '../api/generateVariants';
import type { Variant, VariantMetrics } from '../types';

export const MAX_AUTO_GENERATED_VARIANTS = 3;

function stringNames(value: unknown): string[] {
  if (!Array.isArray(value)) return [];
  return value.filter((item): item is string => typeof item === 'string' && item.trim().length > 0);
}

function attributeIdsFrom(dto: GeneratedVariantDto): string[] {
  const buckets = dto.attributesForVariant ?? {};
  return [
    ...stringNames(buckets.performance),
    ...stringNames(buckets.product),
    ...stringNames(buckets.store),
  ];
}

function pickVariantName(dto: GeneratedVariantDto): string | undefined {
  const raw = dto.variantName ?? dto.variant_name;
  if (typeof raw !== 'string') return undefined;
  const name = raw.trim();
  return name.length > 0 ? name : undefined;
}

function optionalNumber(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

function optionalBoolean(value: unknown): boolean | null {
  return typeof value === 'boolean' ? value : null;
}

function optionalString(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const trimmed = value.trim();
  return trimmed.length > 0 ? trimmed : null;
}

export function parseVariantMetrics(value: unknown): VariantMetrics | null {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return null;
  const raw = value as Record<string, unknown>;
  return {
    attributeCount: optionalNumber(raw.attributeCount),
    average: optionalNumber(raw.average),
    normalized: optionalNumber(raw.normalized),
    clusterMin: optionalNumber(raw.clusterMin),
    clusterMax: optionalNumber(raw.clusterMax),
    clusterCount: optionalNumber(raw.clusterCount),
    fitPercent: optionalNumber(raw.fitPercent),
    storeCount: optionalNumber(raw.storeCount),
    smallStoreOverride: optionalBoolean(raw.smallStoreOverride),
    kValueCount: optionalNumber(raw.kValueCount),
    startingPoints: optionalNumber(raw.startingPoints),
    optionCount: optionalNumber(raw.optionCount),
    summary: optionalString(raw.summary),
  };
}

/** True for generated cards; CUSTOM strategy or an explicit false flag is a custom variant. */
export function isAutoGeneratedVariant(dto: GeneratedVariantDto): boolean {
  if (dto.isAutoGenerated === true) return true;
  if (dto.isAutoGenerated === false) return false;
  return dto.strategyUsed !== 'CUSTOM';
}

export function hasCustomVariant(variants: Array<{ isAutoGenerated: boolean }>): boolean {
  return variants.some((variant) => !variant.isAutoGenerated);
}

/** First 3 auto-generated (BE order) plus at most one custom, appended after the autos. */
export function capReviewVariants(variants: Variant[]): Variant[] {
  const autos = variants
    .filter((variant) => variant.isAutoGenerated)
    .slice(0, MAX_AUTO_GENERATED_VARIANTS);
  const custom = variants.find((variant) => !variant.isAutoGenerated);
  return custom ? [...autos, custom] : autos;
}

export function mapGeneratedVariant(dto: GeneratedVariantDto): Variant {
  return {
    id: dto.variantId.trim(),
    name: pickVariantName(dto),
    labelKey: 'review.variantCode',
    attributeIds: attributeIdsFrom(dto),
    removed: dto.isDiscarded === true,
    isAutoGenerated: isAutoGeneratedVariant(dto),
    aiSummary: optionalString(dto.aiSummary),
    metrics: parseVariantMetrics(dto.metrics),
  };
}

export function mapGeneratedVariants(data: GenerateVariantsResponse): Variant[] {
  return capReviewVariants(data.variants.map(mapGeneratedVariant));
}
