import { env } from '@config/env';
import { apiClient } from '@shared/services';

/** `POST /v1/clustering/plans/attributes/variants/{clusterPlanCode}`. */
export const GENERATE_VARIANTS_ENDPOINT = `${env.goApiBaseUrl}/v1/clustering/plans/attributes/variants`;

export interface GeneratedVariantAttributes {
  product?: string[];
  performance?: string[];
  store?: string[];
}

export interface GeneratedVariantMetrics {
  attributeCount?: number | null;
  average?: number | null;
  normalized?: number | null;
  clusterMin?: number | null;
  clusterMax?: number | null;
  clusterCount?: number | null;
  fitPercent?: number | null;
  storeCount?: number | null;
  smallStoreOverride?: boolean | null;
  kValueCount?: number | null;
  startingPoints?: number | null;
  optionCount?: number | null;
  summary?: string | null;
}

export interface GeneratedVariantDto {
  variantId: string;
  clusterPlanCode?: string;
  description?: string;
  variantName?: string;
  variant_name?: string;
  isDiscarded?: boolean;
  isFinal?: boolean;
  attributesForVariant?: GeneratedVariantAttributes;
  isAutoGenerated?: boolean;
  aiSummary?: string | null;
  metrics?: GeneratedVariantMetrics | null;
  strategyUsed?: string;
}

export interface GenerateVariantsResponse {
  strategy?: string;
  variants: GeneratedVariantDto[];
}

function unwrapData(payload: unknown): unknown {
  if (typeof payload === 'object' && payload !== null && 'data' in payload) {
    return (payload as { data: unknown }).data;
  }
  return payload;
}

function endpointFor(clusterPlanCode: string): string {
  const code = clusterPlanCode.trim();
  if (!code) throw new Error('clusterPlanCode is required');
  return `${GENERATE_VARIANTS_ENDPOINT}/${encodeURIComponent(code)}`;
}

function isVariantDto(value: unknown): value is GeneratedVariantDto {
  if (typeof value !== 'object' || value === null) return false;
  const id = (value as { variantId?: unknown }).variantId;
  return typeof id === 'string' && id.trim().length > 0;
}

function isGenerateVariantsResponse(value: unknown): value is GenerateVariantsResponse {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
  const variants = (value as { variants?: unknown }).variants;
  return Array.isArray(variants);
}

function parseGenerateVariantsResponse(payload: unknown): GenerateVariantsResponse {
  const data = unwrapData(payload);
  if (!isGenerateVariantsResponse(data)) {
    throw new Error('Unexpected generate variants response');
  }
  return {
    ...data,
    variants: data.variants.filter(isVariantDto),
  };
}

/**
 * Generates attribute variants for the plan. No request body — `{}` would still be
 * serialized by `apiClient.post`.
 */
export async function generateVariants(
  clusterPlanCode: string,
): Promise<GenerateVariantsResponse> {
  const payload = await apiClient.post<unknown>(endpointFor(clusterPlanCode));
  return parseGenerateVariantsResponse(payload);
}

/** Resume: same body as POST, already-generated variants for the plan. */
export async function getGeneratedVariants(
  clusterPlanCode: string,
): Promise<GenerateVariantsResponse> {
  const payload = await apiClient.get<unknown>(endpointFor(clusterPlanCode));
  return parseGenerateVariantsResponse(payload);
}
